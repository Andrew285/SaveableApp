package com.rainyday.saveableapp.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Canonical dp scale for the app. Every hardcoded padding, gap, icon/avatar size, corner
 * radius, elevation, etc. should reference one of these instead of writing a literal `N.dp` —
 * one source of truth, and a global density change is a one-line edit.
 *
 * Named after their own value (not a semantic role like "small"/"medium") so a value used for
 * padding in one place and an icon size in another still maps to the same token — usage context
 * already lives at the call site.
 */
object Dimens {
    val d0 = 0.dp
    val d1 = 1.dp
    val d2 = 2.dp
    val d3 = 3.dp
    val d4 = 4.dp
    val d5 = 5.dp
    val d6 = 6.dp
    val d8 = 8.dp
    val d10 = 10.dp
    val d12 = 12.dp
    val d14 = 14.dp
    val d16 = 16.dp
    val d18 = 18.dp
    val d20 = 20.dp
    val d24 = 24.dp
    val d28 = 28.dp
    val d32 = 32.dp
    val d36 = 36.dp
    val d40 = 40.dp
    val d44 = 44.dp
    val d56 = 56.dp
    val d64 = 64.dp
    val d88 = 88.dp
    val d96 = 96.dp
    val d160 = 160.dp
    val d200 = 200.dp
    val d220 = 220.dp
}
